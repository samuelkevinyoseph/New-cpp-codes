#include <iostream>

using namespace std;

int main()
{ 
  cout << (5 > 3) << endl; // true, prints 1
  cout << (5 < 3) << endl; // false, prints 0
  cout << (5 == 5) << endl; // true, prints 1
  cout << (5 != 3) << endl; // true, prints 1
  cout << (5 >= 3) << endl; // true, prints 1
  cout << (5 <= 3) << endl; // false, prints 0
}